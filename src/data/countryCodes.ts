/**
 * Lista combinada completa con destacados primero
 */
export const COUNTRY_CODES: CountryCode[] = [
  ...POPULAR_COUNTRY_CODES,
  ...ALL_WORLD_COUNTRY_CODES.filter(
    (item) => !POPULAR_COUNTRY_CODES.some((p) => p.iso === item.iso)
  ),
];

/**
 * Busca un país por su prefijo telefónico (ej: '+53' -> Cuba)
 */
export function findCountryByCode(prefix: string): CountryCode | undefined {
  const clean = prefix.startsWith("+") ? prefix : `+${prefix}`;
  return (
    POPULAR_COUNTRY_CODES.find((c) => c.code === clean) ||
    ALL_WORLD_COUNTRY_CODES.find((c) => c.code === clean)
  );
}

/**
 * Busca un país por su código ISO (ej: 'CU' -> Cuba)
 */
export function findCountryByIso(iso: string): CountryCode | undefined {
  const clean = iso.toUpperCase();
  return (
    POPULAR_COUNTRY_CODES.find((c) => c.iso === clean) ||
    ALL_WORLD_COUNTRY_CODES.find((c) => c.iso === clean)
  );
}
