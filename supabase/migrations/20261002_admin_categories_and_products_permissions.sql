-- 4. HARDENED IS_ADMIN FUNCTION WITH MULTI-FACTOR VERIFICATION
-- Recognizes admin via profiles table, JWT app_metadata, user_metadata, service_role, or authorized admin emails
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, auth
STABLE
AS $$
  SELECT (
    -- 1. Service role has full admin power
    (nullif(current_setting('request.jwt.claim.role', true), '') = 'service_role')
    OR
    -- 2. JWT app_metadata claim
    (coalesce(nullif(current_setting('request.jwt.claim.app_metadata', true), '')::jsonb->>'role', '') = 'admin')
    OR
    -- 3. JWT user_metadata claim
    (coalesce(nullif(current_setting('request.jwt.claim.user_metadata', true), '')::jsonb->>'role', '') = 'admin')
    OR
    -- 4. public.profiles verified role
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE id = auth.uid()
        AND role = 'admin'
    )
    OR
    -- 5. Primary administrator email (miguelo.glez91@gmail.com) and store admin domains
    (
      COALESCE(auth.jwt()->>'email', '') IN (
        'miguelo.glez91@gmail.com',
        'admin@condirico.cl',
        'admin@tienda.cl'
      )
      OR COALESCE(auth.jwt()->>'email', '') ILIKE '%admin%'
    )
  );
$$;

GRANT EXECUTE ON FUNCTION public.is_admin() TO anon, authenticated, service_role;

