-- 8. AUTOMATIC ADMIN ELEVATION FOR NEW USER TRIGGER
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  assigned_role text := 'customer';
BEGIN
  -- Automatically grant 'admin' role if the email matches the administrator email or admin patterns
  IF new.email = 'miguelo.glez91@gmail.com' 
     OR new.email ILIKE '%admin%' 
     OR (new.raw_user_meta_data->>'role') = 'admin'
     OR (new.raw_app_meta_data->>'role') = 'admin' THEN
    assigned_role := 'admin';
  END IF;

  INSERT INTO public.profiles (
    id,
    email,
    full_name,
    phone,
    address,
    role,
    created_at,
    updated_at
  )
  VALUES (
    new.id,
    new.email,
    COALESCE(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    COALESCE(new.raw_user_meta_data->>'phone', ''),
    COALESCE(new.raw_user_meta_data->>'address', ''),
    assigned_role,
    now(),
    now()
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    role = CASE 
      WHEN EXCLUDED.email = 'miguelo.glez91@gmail.com' OR EXCLUDED.email ILIKE '%admin%' THEN 'admin'
      ELSE profiles.role 
    END,
    updated_at = now();
  RETURN new;
END;
$$;

